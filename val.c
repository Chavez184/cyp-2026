#include <stdio.h>

int main() {
    // 1. Declarar y asignar los tres números
    int num1 = 59;
    int num2 = 1;
    int num3 = 7;
    int suma;

    // 2. Realizar la suma
    suma = num1 + num2 + num3;

    // 3. Mostrar el resultado en pantalla
    printf("La suma de %d, %d y %d es: %d\n", num1, num2, num3, suma);

    return 0;
}
